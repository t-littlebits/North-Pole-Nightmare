// Generates supabase/catalog.sql from the game's data files, so the database functions that validate shop actions
// always use the same prices, slots and compatibility rules as the game. Re-run after changing any item:
//   npm run gen:catalog      (then run supabase/catalog.sql in the Supabase SQL Editor)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHARACTERS, WEAPONS, SKINS, BOOSTS } from '../src/data/catalog.js';
import { COSMETIC_LIST } from '../src/data/cosmetics.js';
import { MOD_LIST, MOD_CRATE_PRICE, ACHIEVEMENT_MODS } from '../src/data/mods.js';
import { TITLES } from '../src/data/titles.js';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a ? `array[${a.map(q).join(', ')}]::text[]` : 'null::text[]');

export function catalogRows() {
  const rows = [];
  const add = (type, id, o = {}) => rows.push({ type, id, price: o.price ?? 0, slot: o.slot ?? null, parent: o.parent ?? null, source: o.source ?? null, rarity: o.rarity ?? null, weapons: o.weapons ?? null, achievement: !!o.achievement, hidden: !!o.hidden });
  Object.values(CHARACTERS).forEach((c) => add('character', c.id, { price: c.price }));
  Object.values(WEAPONS).forEach((w) => add('weapon', w.id, { price: w.price }));
  Object.values(SKINS).forEach((s) => add('skin', s.id, { price: s.price, parent: s.character, source: s.source, rarity: s.rarity, hidden: s.hidden }));
  COSMETIC_LIST.forEach((c) => add('cosmetic', c.id, { price: c.price, slot: c.slot, rarity: c.rarity }));
  MOD_LIST.forEach((m) => add('mod', m.id, { rarity: m.rarity, weapons: m.weapons, achievement: ACHIEVEMENT_MODS.has(m.id) }));
  TITLES.forEach((t) => add('title', t.id, { rarity: t.rarity }));
  Object.values(BOOSTS).forEach((b) => add('boost', b.id));
  add('crate', 'mod_crate', { price: MOD_CRATE_PRICE });
  return rows;
}

export function buildCatalogSql() {
  const rows = catalogRows();
  const values = rows.map((r) => `  (${[q(r.type), q(r.id), q(r.price), q(r.slot), q(r.parent), q(r.source), q(r.rarity), arr(r.weapons), q(r.achievement), q(r.hidden)].join(', ')})`).join(',\n');
  const keys = rows.map((r) => `(${q(r.type)}, ${q(r.id)})`).join(', ');
  return `-- GENERATED by scripts/gen-catalog-sql.mjs from the game's data files. Do not edit by hand.
-- Run this in the Supabase SQL Editor after update-6-fast-actions.sql, and again whenever items change (npm run gen:catalog).
insert into public.catalog_items (type, id, price, slot, parent, source, rarity, weapons, achievement, hidden) values
${values}
on conflict (type, id) do update set price = excluded.price, slot = excluded.slot, parent = excluded.parent, source = excluded.source,
  rarity = excluded.rarity, weapons = excluded.weapons, achievement = excluded.achievement, hidden = excluded.hidden;

-- remove items that no longer exist in the game
delete from public.catalog_items c where not exists (select 1 from (values ${keys}) as v(t, i) where v.t = c.type and v.i = c.id);
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../supabase/catalog.sql');
  fs.writeFileSync(out, buildCatalogSql());
  console.log(`wrote ${out}`);
}
